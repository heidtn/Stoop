Import("env")

"""This program goes through the web/ directory and generates a C header file 
containing all the HTML files as gzipped byte arrays.  This allows the HTML to
be embedded in the firmware binary, so that it can be served by the device without
needing an external filesystem.

This code was AI generated, but human reviewed and edited.
"""

Import("env")

import gzip
import pathlib
import re

PROJECT = pathlib.Path(env.subst("$PROJECT_DIR"))

web_opt = env.GetProjectOption("custom_web_dir", None)
if not web_opt:
    print("[embed_web] no custom_web_dir set, skipping")
else:
    WEB_DIR = PROJECT / web_opt
    OUT = WEB_DIR.parent / "web_assets.h"

    def ident(rel: pathlib.Path) -> str:
        name = re.sub(r"[^0-9A-Za-z]+", "_", rel.with_suffix("").as_posix())
        name = name.strip("_").upper()
        if not name or name[0].isdigit():
            name = "_" + name
        return name

    def main():
        if not WEB_DIR.is_dir():
            print(f"[embed_web] {web_opt} not found, skipping")
            return

        files = sorted(WEB_DIR.rglob("*.html"))
        if not files:
            print(f"[embed_web] no .html under {web_opt}, skipping")
            return

        lines = [
            "// Generated by tools/embed_web.py -- do not edit.",
            "#pragma once",
            "#include <stddef.h>",
            "#include <stdint.h>",
            "",
        ]

        seen = {}
        for path in files:
            rel = path.relative_to(WEB_DIR)
            name = ident(rel)
            if name in seen:
                raise ValueError(
                    f"web asset collision: {rel} and {seen[name]} both -> {name}"
                )
            seen[name] = rel

            gz = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
            body = ",".join(str(b) for b in gz)

            lines += [
                f"// {rel.as_posix()}  ({path.stat().st_size} -> {len(gz)} gzipped)",
                f"const uint8_t {name}_HTML_GZ[] = {{{body}}};",
                f"const size_t {name}_HTML_GZ_LEN = {len(gz)};",
                "",
            ]
            print(f"[embed_web] {rel.as_posix()} -> {name}_HTML_GZ ({len(gz)} bytes)")

        new = "\n".join(lines)
        if not OUT.exists() or OUT.read_text() != new:
            OUT.write_text(new)
            print(f"[embed_web] wrote {OUT.relative_to(PROJECT)}")
        else:
            print("[embed_web] unchanged")

    main()
    # make the generated header findable from the example's own sources
    env.Append(CPPPATH=[str(WEB_DIR.parent)])